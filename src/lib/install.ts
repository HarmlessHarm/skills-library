import { config, repo, type AgentConfig } from './config';
import { withBase } from './url';

/** One install command for one agent. Every snippet is rendered into the
    page; the header dropdown decides which one is visible. */
export interface InstallSnippet {
  agent: AgentConfig;
  script: string;
}

/** Expands the `{placeholder}` tokens allowed in config.yaml agent entries. */
function expand(template: string, tokens: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (match, key) => tokens[key] ?? match);
}

/**
 * The plugin and marketplace name, as generated by scripts/build-assets.mjs:
 * the repository name in kebab-case. Kept in step with that script.
 */
const pluginName = (repo.name || 'skills-library')
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .replace(/[^a-zA-Z0-9]+/g, '-')
  .replace(/^-+|-+$/g, '')
  .toLowerCase();

const tokens = {
  owner: repo.owner,
  repo: repo.name,
  slug: repo.slug,
  branch: repo.branch,
  plugin: pluginName,
};

/** Site-relative URL of a skill's downloadable `.skill` archive. */
export function downloadUrl(name: string): string {
  return withBase(`/downloads/${name}.skill`);
}

/** Link to the skill's source folder in the GitHub repository. */
export function sourceUrl(name: string): string {
  return `https://github.com/${repo.slug}/tree/${repo.branch}/skills/${name}`;
}

/** `npx skills add` for the whole library, one per agent. */
export function librarySnippets(): InstallSnippet[] {
  return config.agents.map((agent) => ({
    agent,
    script: `npx skills add ${repo.slug} -a ${agent.skillsAgent}`,
  }));
}

/** `npx skills add` for a single skill, one per agent. */
export function skillSnippets(name: string): InstallSnippet[] {
  return config.agents.map((agent) => ({
    agent,
    script: `npx skills add ${repo.slug} --skill ${name} -a ${agent.skillsAgent}`,
  }));
}

/**
 * The plugin install for every agent that has a `plugin` entry in
 * config.yaml. Agents without one are left out, and get no plugin block.
 */
export function pluginSnippets(): InstallSnippet[] {
  // flatMap rather than filter+map so the narrowing survives into the body.
  return config.agents.flatMap((agent) =>
    agent.plugin ? [{ agent, script: expand(agent.plugin, tokens) }] : [],
  );
}
